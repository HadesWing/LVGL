/**
 * @file yuv2rgb.h
 * @brief YUV420P → RGB565 转换 + 等比适配（上屏的最后一步）
 *
 * 【为什么单独一个模块】
 *   这一步既不属于"解码"（那是 vdec 的事），也不属于"界面"（那是 ui_call 的事），
 *   而是两者的接缝。接缝最容易藏 bug，所以单独拎出来：不依赖 LVGL、不依赖 SDL，
 *   可以被 UT 直接调用，逐像素核对。上屏那一路的数值验收就是靠它可测。
 *
 * 【为什么输出 RGB565 而不是 RGB888】
 *   1) 显存/内存减半：288x216 一帧 565 是 124KB，888 是 186KB。
 *   2) LVGL 的 lv_image 原生支持 LV_COLOR_FORMAT_RGB565，无需再转。
 *   3) 在 PC 上显示器是 888，但它内部把 565 拉回 888 是可逆的（补高位），
 *      所以抓屏取回来的像素再量化回 565 就是原值 —— 这让"抓屏 vs 参考帧"
 *      可以做到逐像素相同，而不是只能看 PSNR。见 scripts/disp_compare.py。
 *
 * 【为什么用 BT.601 有限量程（Y:16~235, UV:128±112）而不是全量程】
 *   摄像头/编码器给的就是这个（H.264 默认 video_full_range_flag=0）。
 *   按全量程换算会把黑场抬成灰（16 被当成 16/255 的亮），整幅发白。
 *   这个坑在做视频类项目里几乎人人踩过一次。
 */
#ifndef YUV2RGB_H
#define YUV2RGB_H

#include <stdbool.h>
#include <stdint.h>

#include "vdec.h"

/**
 * 等比缩放：把 sw×sh 的画面装进 bw×bh 的框，保持宽高比，返回实际显示尺寸。
 * 只算尺寸，不碰像素 —— 调用方按算出来的尺寸调控件大小即可，不需要画黑边。
 *
 * 例：640×480 → 框 288×216，得 288×216；640×360 → 得 288×162（上下留 27px 空）；
 *     320×240 → 得 288×216。
 *
 * 用交叉相乘比较  sw/bw 与 sh/bh，全程整数，不受浮点舍入影响（板子上也一样）。
 * 返回 false 表示参数非法（0 或负数），此时不写 ow / oh。
 */
bool yuv2rgb_fit(int sw, int sh, int bw, int bh, int *ow, int *oh);

/**
 * 单像素 BT.601 有限量程 → RGB565。
 * 单独暴露是为了 UT 能用"标准色"核对（纯黑/纯白/三原色），
 * 那些用例比"整幅 PSNR"更能定位是系数错了还是采样错了。
 */
uint16_t yuv2rgb_565_px(int y, int u, int v);

/**
 * 整帧缩放转换：把 f 缩放到 dw×dh 写进 dst（RGB565，无符号 16 位，本机字节序）。
 *
 * 采样方式是最近邻（像素中心对齐）：
 *     sx = (2*x + 1) * sw / (2 * dw)
 * 不用双线性是刻意的 —— 最近邻是**确定性**的，Python 那边能用同一个公式
 * 复现出一模一样的参考图；双线性会引入浮点舍入差异，比对时说不清是谁的错。
 * 代价是缩放后边缘有点硬，但 640×480 → 288×216 只缩到 45%，肉眼可接受。
 *
 * dst 必须至少有 dw*dh 个 uint16_t 的空间。f->w/h 或 dw/dh <= 0 时什么都不做，
 * 返回 false（绝不写 dst，避免半帧脏数据）。
 */
bool yuv2rgb_565(const vframe_t *f, uint16_t *dst, int dw, int dh);

#endif /* YUV2RGB_H */
